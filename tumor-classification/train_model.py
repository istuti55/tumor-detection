# --- 3D Feature Visualization ---

import tensorflow as tf
import numpy as np
from sklearn.decomposition import PCA
import plotly.express as px
import plotly.io as pio

pio.renderers.default = 'notebook_connected'


inputs = tf.keras.Input(shape=(224, 224, 3))
x = inputs
for layer in model.layers[:-2]:
    x = layer(x)
feature_extractor = tf.keras.Model(inputs=inputs, outputs=x)

sample_features = []
sample_labels = []

for images, lbls in test_ds.take(40):
    feats = feature_extractor.predict(images)
    sample_features.append(feats)
    sample_labels.extend(lbls.numpy())

features = np.concatenate(sample_features)
labels = np.array(sample_labels)

features_flat = features.reshape(features.shape[0], -1)

pca = PCA(n_components=3)
features_3d = pca.fit_transform(features_flat)

# --- Create 3D scatter plot ---
fig = px.scatter_3d(
    x=features_3d[:, 0],
    y=features_3d[:, 1],
    z=features_3d[:, 2],
    color=[class_names[i] for i in labels],
    hover_name=[f"Class: {class_names[i]}" for i in labels],
    title="3D VGG16 Feature Space Visualization",
    labels={'x': 'PCA 1', 'y': 'PCA 2', 'z': 'PCA 3'},
    width=700,
    height=500
)

fig.update_traces(marker=dict(size=5, opacity=0.8))
fig.update_layout(
    legend_title_text="Classes",
    margin=dict(l=0, r=130, b=0, t=40)
)

fig.show()