import tensorflow as tf
import matplotlib.pyplot as plt
import os

# Set dataset directories
train_dir = r"/content/drive/MyDrive/MIR Images/Training"
test_dir  = r"/content/drive/MyDrive/MIR Images/Testing"

# Set Image and Batch Sizes (VGG16 expects 224x224 images)
IMAGE_SIZE = (224, 224)
BATCH_SIZE = 32

# Split Training data into 80% Training and 20% Validation
train_ds = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    validation_split=0.2,       # 20% data for validation
    subset='training',
    seed=123,
    image_size=IMAGE_SIZE,
    batch_size=BATCH_SIZE,
    label_mode='int'
)

val_ds = tf.keras.utils.image_dataset_from_directory(
    train_dir,
    validation_split=0.2,
    subset='validation',
    seed=123,
    image_size=IMAGE_SIZE,
    batch_size=BATCH_SIZE,
    label_mode='int'
)

# Load Testing data
test_ds = tf.keras.utils.image_dataset_from_directory(
    test_dir,
    image_size=IMAGE_SIZE,
    batch_size=BATCH_SIZE,
    label_mode='int',
    shuffle=False
)

# Check class names
class_names = train_ds.class_names
print("Class Names:", class_names)

# Normalize pixel values (0–255 → 0–1)
normalization_layer = tf.keras.layers.Rescaling(1./255)

train_ds = train_ds.map(lambda x, y: (normalization_layer(x), y))
val_ds = val_ds.map(lambda x, y: (normalization_layer(x), y))
test_ds = test_ds.map(lambda x, y: (normalization_layer(x), y))

# Prefetch for faster performance
AUTOTUNE = tf.data.AUTOTUNE
train_ds = train_ds.prefetch(buffer_size=AUTOTUNE)
val_ds = val_ds.prefetch(buffer_size=AUTOTUNE)
test_ds = test_ds.prefetch(buffer_size=AUTOTUNE)

# Visualize sample images
plt.figure(figsize=(8, 8))
for images, labels in train_ds.take(1):
    for i in range(9):
        ax = plt.subplot(3, 3, i + 1)
        plt.imshow(images[i].numpy())
        plt.title(class_names[labels[i]])
        plt.axis("off")
plt.show()

from tensorflow.keras.applications import VGG16
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, Flatten, Dropout
from tensorflow.keras.optimizers import Adam

IMAGE_SHAPE = (224, 224, 3)

base_model = VGG16(
    include_top=False,           # Remove top fully connected layers
    weights='imagenet',          # Use pretrained ImageNet weights
    input_shape=IMAGE_SHAPE
)

#  Freeze Layers

for layer in base_model.layers:
    layer.trainable = False

# Unfreeze the last 3 layers
for layer in base_model.layers[-3:]:
    layer.trainable = True

#  Build the Complete Model
model = Sequential([
    base_model,                         # Pre-trained VGG16 base
    Flatten(),                          # Flatten to 1D
    Dropout(0.3),                       # Regularization
    Dense(128, activation='relu'),      # Hidden dense layer
    Dropout(0.2),                       # Additional regularization
    Dense(len(class_names), activation='softmax')  # Output layer for classification
])



model.compile(
    optimizer=Adam(learning_rate=0.0001),
    loss='sparse_categorical_crossentropy',
    metrics=['sparse_categorical_accuracy']
)

EPOCHS = 30
history = model.fit(
    train_ds,
    epochs=EPOCHS,
    validation_data=val_ds
)

# Save the entire trained model
model.save("model.h5")

#  Plot Training & Validation Accuracy and Loss
plt.figure(figsize=(8,4))
plt.grid(True)


plt.plot(history.history['sparse_categorical_accuracy'], '.-g', linewidth=2)
plt.plot(history.history['val_sparse_categorical_accuracy'], '.--b', linewidth=2)


plt.plot(history.history['loss'], '.-r', linewidth=2)
plt.plot(history.history['val_loss'], '.--y', linewidth=2)


plt.title('Model Training History')
plt.xlabel('Epoch')
plt.ylabel('Value')

plt.legend(
    ['Train Accuracy', 'Val Accuracy', 'Train Loss', 'Val Loss'],
    loc='upper left',
    bbox_to_anchor=(1, 1),

)

plt.show()

